import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const DATA = path.join(__dirname, '..', 'data');

const PRESERVE_JSON = ['vocab-54-topics.json', 'chart-53-bank.json', 'chart-53-formula.json', 'chart-53-exam-visuals.json', 'chart-53-answers.json', 'essay-54-templates.json', 'expressions-54-bank.json'];

function writeJson(name, obj) {
  if (PRESERVE_JSON.includes(name)) {
    console.log('↷ preserved', name, '(chỉnh trực tiếp trong data/)');
    return;
  }
  fs.writeFileSync(path.join(DATA, name), JSON.stringify(obj, null, 2) + '\n', 'utf8');
  console.log('✓', name);
}

function parseTerms(lines) {
  return lines
    .map((line) => {
      const m = line.match(/^-\s*(.+?):\s*(.+)$/);
      if (!m) return null;
      return { ko: m[1].trim(), vi: m[2].trim() };
    })
    .filter(Boolean);
}

